#!/usr/bin/env python3
"""Move FineType's table macros out of its Rust entry point, for the managed build.

    move-table-macros.py LIB_RS HEADER_OUT

FineType registers `ft_validate` and `ft_profile` as SQL table macros with a
`CREATE OR REPLACE MACRO` on the database being opened. Loaded from an
extension file that is one `LOAD finetype`; compiled into DuckDB it runs on
every database DuckDB opens, so every database opened read-write is left
holding the two macros, and a database opened read-only gets neither. DuckDB's
C API cannot register a macro anywhere else, so FineType's Rust cannot do
better. DuckDB's C++ can: finetype_static_entry.cpp registers them in the
system catalog, which is where a built-in function lives and is not written to
any file.

This script does the two halves that touch FineType's source, crates/
finetype-duckdb/src/lib.rs at the pinned commit:

  1. It reads each macro's name, parameters and SELECT out of the Rust
     constants and writes them to HEADER_OUT as a table the entry point
     registers, so the SQL is FineType's own at the pin and Brightfield keeps no
     copy to fall behind.
  2. It turns `register_table_macro` into a function that registers nothing, so
     FineType no longer runs the CREATE.

Every edit and every read is counted. A FineType that adds a table macro,
registers one another way, or rewrites the function fails the build here, with
the reason, and never builds a DuckDB that silently lacks a macro or writes one.
"""
import re
import sys

RAW_DELIMITER = "FTSQL"


def fail(message):
    sys.exit(f"move-table-macros: {message}")


def main():
    if len(sys.argv) != 3:
        fail("usage: move-table-macros.py LIB_RS HEADER_OUT")
    lib_rs, header_out = sys.argv[1:3]
    with open(lib_rs, encoding="utf-8") as f:
        text = f.read()

    # The constants: `const NAME: &str = r#"CREATE OR REPLACE MACRO f(a, b) AS TABLE <select>"#;`
    constant = re.compile(
        r'^const (\w+): &str = r#"CREATE OR REPLACE MACRO (\w+)\(([^)]*)\) AS TABLE\s(.*?)"#;',
        re.DOTALL | re.MULTILINE,
    )
    macros = {}
    for match in constant.finditer(text):
        const, name, parameters, select = match.groups()
        parameters = [p.strip() for p in parameters.split(",") if p.strip()]
        for parameter in parameters:
            if not re.fullmatch(r"\w+", parameter):
                fail(f"{name}'s parameter '{parameter}' is not a plain name; a default value needs a named parameter here")
        if len(parameters) > 7:
            fail(f"{name} has {len(parameters)} parameters; DuckDB's DefaultTableMacro holds seven")
        if f"){RAW_DELIMITER}\"" in select:
            fail(f"{name}'s SQL contains the raw-string delimiter ){RAW_DELIMITER}\"")
        macros[const] = (name, parameters, select.strip().rstrip(";").rstrip())

    # The calls that register them, and nothing else that creates a macro.
    calls = re.findall(r"register_table_macro\(&con, (\w+)\);", text)
    if not calls:
        fail(f"{lib_rs} has no register_table_macro(&con, ...) call; FineType registers its table macros another way now")
    if sorted(calls) != sorted(macros):
        fail(f"the macros registered ({sorted(calls)}) are not the CREATE OR REPLACE MACRO constants found ({sorted(macros)})")
    creates = len(re.findall(r"CREATE (?:OR REPLACE )?(?:TEMP(?:ORARY)? )?MACRO", text))
    if creates != len(macros):
        fail(f"{lib_rs} has {creates} CREATE MACRO statements and {len(macros)} of them are table-macro constants")

    body = "    let _ = con.execute_batch(sql);\n"
    if text.count(body) != 1 or text.count("fn register_table_macro(con: &duckdb::Connection, sql: &str) {\n" + body) != 1:
        fail("register_table_macro is no longer the one-line execute_batch this script replaces")
    patched = text.replace(body, "    let _ = (con, sql); // Brightfield's managed build registers the table macros from C++.\n")

    lines = [
        "// Generated by scripts/duckdb-managed/finetype/move-table-macros.py from FineType's",
        "// crates/finetype-duckdb/src/lib.rs at the pinned commit. Not edited by hand.",
        "#pragma once",
        '#include "duckdb/catalog/default/default_table_functions.hpp"',
        "",
        "static const duckdb::DefaultTableMacro BRIGHTFIELD_FINETYPE_TABLE_MACROS[] = {",
    ]
    for const in calls:
        name, parameters, select = macros[const]
        names = ", ".join([f'"{p}"' for p in parameters] + ["nullptr"])
        lines.append(f'    {{DEFAULT_SCHEMA, "{name}", {{{names}}}, {{{{nullptr, nullptr}}}},')
        lines.append(f'     R"{RAW_DELIMITER}({select}){RAW_DELIMITER}"}},')
    lines.append("    {nullptr, nullptr, {nullptr}, {{nullptr, nullptr}}, nullptr}};")
    with open(header_out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    with open(lib_rs, "w", encoding="utf-8") as f:
        f.write(patched)
    print(f"move-table-macros: {', '.join(macros[c][0] for c in calls)} moved to {header_out}", file=sys.stderr)


if __name__ == "__main__":
    main()
